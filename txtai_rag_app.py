#!/usr/bin/env python3
"""
txtai RAG App — semantic search + Retrieval-Augmented Generation with citations.

This is the Python code behind the txtai RAG space app. It mirrors the app's
four tabs in a command-line program:

    Library  -> load .txt / .md files (or pasted text), chunk them, index them
    Search   -> raw similarity search with scores  (Embeddings.search)
    Ask      -> RAG question-answering grounded in the retrieved context,
                returning a citation/reference to the source chunk (RAG)
    About    -> printed at the bottom of --help / in this docstring

txtai is an all-in-one open-source embeddings database for semantic search,
LLM orchestration and language-model workflows (Apache 2.0).
Docs: https://neuml.github.io/txtai/pipeline/llm/rag/

Install:
    pip install txtai[pipeline]

    # Smaller install if you only want search (no LLM generation):
    pip install txtai

Run:
    # 1. Demo with the built-in sample data from the official txtai docs
    python txtai_rag_app.py --demo
    python txtai_rag_app.py --demo --search "lottery winnings"
    python txtai_rag_app.py --demo --ask "What was won?"

    # 2. Your own documents: index every .txt / .md file in a folder
    python txtai_rag_app.py --data ./docs --ask "What does the refund policy say?"
    python txtai_rag_app.py --data ./docs --search "refund deadline"

    # 3. Interactive mode (type questions, 'search: ...' for raw search, 'quit' to exit)
    python txtai_rag_app.py --data ./docs --interactive

    # 4. Save / reuse an index instead of re-indexing every run
    python txtai_rag_app.py --data ./docs --save-index ./index
    python txtai_rag_app.py --load-index ./index --ask "What was won?"

Notes on how this differs from a hosted demo:
    Real txtai ranks results with neural embeddings (default model:
    sentence-transformers/all-MiniLM-L6-v2), not TF-IDF / keyword overlap.
    Answers are generated by a local LLM (default: Qwen/Qwen3-0.6B), so the
    first run downloads model weights from Hugging Face.
"""

from __future__ import annotations

import argparse
import os
import sys
import textwrap
from dataclasses import dataclass, field
from pathlib import Path

# ---------------------------------------------------------------------------
# Sample data — the exact example corpus from the official txtai RAG docs.
# Try it with the question: "What was won?"
# ---------------------------------------------------------------------------

SAMPLE_DATA = [
    "US tops 5 million confirmed virus cases",
    "Canada's last fully intact ice shelf has suddenly collapsed, "
    "forming a Manhattan-sized iceberg",
    "Beijing mobilises invasion craft along coast as Taiwan tensions escalate",
    "The National Park Service warns against sacrificing slower friends "
    "in a bear attack",
    "Maine man wins $1M from $25 lottery ticket",
    "Make huge profits without work, earn up to $100,000 a day",
]

DEFAULT_LLM = "Qwen/Qwen3-0.6B"

RAG_TEMPLATE = """
Answer the following question using the provided context.
Only include information specifically discussed in the context.
If the context does not contain the answer, say you don't know.

Question:
{question}

Context:
{context}
"""


# ---------------------------------------------------------------------------
# Library: loading + chunking
# ---------------------------------------------------------------------------


@dataclass
class Chunk:
    """One indexed piece of a document. `uid` is the citation target."""

    uid: str          # e.g. "refund-policy.md#2"
    source: str       # file name or "sample"
    text: str


def chunk_text(text: str, source: str, size: int = 800, overlap: int = 100) -> list[Chunk]:
    """Split text into overlapping chunks on paragraph / sentence boundaries.

    Chunking matters for RAG: too large and retrieval drags in noise,
    too small and the answer loses its context. 800 chars / 100 overlap
    is a reasonable starting point for prose documents.
    """
    text = " ".join(text.split())  # normalise whitespace
    if not text:
        return []

    pieces, start, index = [], 0, 0
    while start < len(text):
        end = min(start + size, len(text))
        # Prefer to break on a sentence / space boundary, not mid-word.
        if end < len(text):
            cut = max(text.rfind(". ", start, end), text.rfind(" ", start, end))
            if cut > start:
                end = cut + 1
        pieces.append(
            Chunk(uid=f"{source}#{index}", source=source, text=text[start:end].strip())
        )
        index += 1
        if end >= len(text):
            break
        start = max(end - overlap, start + 1)
    return pieces


def load_folder(folder: str | Path) -> list[Chunk]:
    """Load every .txt / .md file under `folder` (recursively) as chunks."""
    folder = Path(folder)
    if not folder.is_dir():
        raise SystemExit(f"Data folder not found: {folder}")

    chunks: list[Chunk] = []
    for path in sorted(folder.rglob("*")):
        if path.suffix.lower() in {".txt", ".md"} and path.is_file():
            chunks.extend(chunk_text(path.read_text(encoding="utf-8", errors="ignore"),
                                     source=path.name))
    if not chunks:
        raise SystemExit(f"No .txt or .md files found in: {folder}")
    return chunks


def sample_chunks() -> list[Chunk]:
    """The built-in demo corpus, one chunk per headline."""
    return [Chunk(uid=f"sample#{i}", source="sample", text=t)
            for i, t in enumerate(SAMPLE_DATA)]


# ---------------------------------------------------------------------------
# Core app: Embeddings index (Search) + RAG pipeline (Ask)
# ---------------------------------------------------------------------------


@dataclass
class TxtaiRAGApp:
    chunks: list[Chunk] = field(default_factory=list)
    llm_path: str = DEFAULT_LLM
    context: int = 3          # top-n chunks passed to the LLM as context
    _embeddings: object = field(default=None, repr=False)
    _rag: object = field(default=None, repr=False)
    _by_uid: dict = field(default_factory=dict, repr=False)

    # -- Library ---------------------------------------------------------
    def build_index(self, save_path: str | None = None):
        """Index all chunks. This is txtai's Embeddings.index() step.

        Rows are (uid, text, None): giving each chunk a stable uid is what
        lets search results and RAG citations point back to the source.
        content=True stores the text in the index so it can be retrieved.
        """
        from txtai import Embeddings

        self._by_uid = {c.uid: c for c in self.chunks}
        self._embeddings = Embeddings(content=True)
        self._embeddings.index([(c.uid, c.text, None) for c in self.chunks])
        if save_path:
            self._embeddings.save(save_path)
        print(f"Indexed {len(self.chunks)} chunk(s) "
              f"from {len({c.source for c in self.chunks})} source(s).")
        return self

    def load_index(self, load_path: str, chunks: list[Chunk]):
        """Reload a previously saved index plus its chunk list."""
        from txtai import Embeddings

        self.chunks = chunks
        self._by_uid = {c.uid: c for c in chunks}
        self._embeddings = Embeddings(content=True)
        self._embeddings.load(load_path)
        print(f"Loaded index from {load_path} ({len(chunks)} chunk(s)).")
        return self

    # -- Search tab --------------------------------------------------------
    def search(self, query: str, limit: int = 5) -> list[tuple[Chunk, float]]:
        """Raw similarity search. Returns [(chunk, score), ...], best first."""
        if self._embeddings is None:
            raise RuntimeError("Index not built — call build_index() first.")
        results = self._embeddings.search(query, limit=limit)
        # txtai's search rows are not always 2-tuples: depending on the
        # version and index options they can be (uid, score, text) triples
        # or dicts. Unpack defensively instead of assuming (uid, score).
        found: list[tuple[Chunk, float]] = []
        for row in results:
            if isinstance(row, dict):
                uid = row.get("id", row.get("uid"))
                score = row.get("score", 0.0)
            else:
                uid, score = row[0], row[1]
            if uid in self._by_uid:
                found.append((self._by_uid[uid], float(score)))
        return found

    def print_search(self, query: str, limit: int = 5):
        print(f"\nSearch: {query!r}")
        for chunk, score in self.search(query, limit=limit):
            print(f"  [{score:.4f}] ({chunk.uid}) {chunk.text}")

    # -- Ask tab -----------------------------------------------------------
    def _get_rag(self):
        """Create the RAG pipeline once, on first use (loads the LLM).

        output='reference' asks the pipeline to include the uid of the
        context chunk the answer most likely came from — the citation.
        Current txtai returns that as a dict {"answer": ..., "reference": ...};
        ask() normalizes older tuple shapes too.
        """
        if self._rag is None:
            from txtai import RAG

            self._rag = RAG(
                self._embeddings,
                self.llm_path,
                template=RAG_TEMPLATE,
                context=self.context,
                output="reference",
                system="You are a friendly assistant. "
                       "You answer questions from users using only the provided context.",
            )
        return self._rag

    def ask(self, question: str) -> tuple[str, list[tuple[Chunk, float]], str | None]:
        """Run the full RAG flow: retrieve -> ground -> generate -> cite.

        Returns (answer, retrieved_chunks_with_scores, citation_uid).
        """
        retrieved = self.search(question, limit=self.context)
        # The RAG pipeline's return shape varies by txtai version:
        # current versions return a dict {"answer": ..., "reference": ...};
        # older ones return (name, answer, reference) or (answer, reference)
        # tuples. Normalize all shapes instead of assuming one.
        result = self._get_rag()(question)
        if isinstance(result, list) and result and isinstance(result[0], dict):
            result = result[0]
        if isinstance(result, dict):
            answer = result.get("answer") or result.get("text") or ""
            reference = result.get("reference")
        elif isinstance(result, (list, tuple)):
            if len(result) == 3:
                _name, answer, reference = result
            elif len(result) == 2:
                answer, reference = result
            else:
                answer, reference = str(result), None
        else:
            answer, reference = str(result), None
        citation = reference if reference in self._by_uid else (
            retrieved[0][0].uid if retrieved else None
        )
        return str(answer).strip(), retrieved, citation

    def print_ask(self, question: str):
        answer, retrieved, citation = self.ask(question)
        print(f"\nQ: {question}")
        print(f"A: {answer}")
        if citation:
            print(f"Citation: [{citation}] {self._by_uid[citation].text}")
        print("Retrieved context:")
        for chunk, score in retrieved:
            print(f"  [{score:.4f}] ({chunk.uid}) {chunk.text}")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        description="txtai RAG app — index documents, search them, "
                    "and ask questions with citations.",
        epilog=textwrap.dedent("""\
            examples:
              %(prog)s --demo --ask "What was won?"
              %(prog)s --demo --search "lottery"
              %(prog)s --data ./docs --ask "What is the refund policy?"
              %(prog)s --data ./docs --interactive
            """),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    src = p.add_mutually_exclusive_group(required=True)
    src.add_argument("--demo", action="store_true",
                     help="use the built-in sample corpus from the txtai docs")
    src.add_argument("--data", metavar="FOLDER",
                     help="folder of .txt / .md files to index")
    src.add_argument("--load-index", metavar="PATH",
                     help="load a saved index built from the sample corpus")

    p.add_argument("--ask", metavar="QUESTION", help="ask one question (RAG)")
    p.add_argument("--search", metavar="QUERY", help="run one raw similarity search")
    p.add_argument("--interactive", action="store_true",
                   help="chat loop: questions, or 'search: <query>', 'quit' to exit")
    p.add_argument("--model", default=DEFAULT_LLM,
                   help=f"LLM for generation (default: {DEFAULT_LLM}). "
                        "Any Hugging Face / llama.cpp / LiteLLM path txtai supports works.")
    p.add_argument("--context", type=int, default=3,
                   help="top-n chunks used as RAG context (default: 3)")
    p.add_argument("--limit", type=int, default=5,
                   help="results shown for --search (default: 5)")
    p.add_argument("--save-index", metavar="PATH", help="save the built index to PATH")
    p.add_argument("--chunk-size", type=int, default=800)
    p.add_argument("--chunk-overlap", type=int, default=100)
    return p.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)

    # Resolve the chunk list (needed either way: indexing, or citations
    # when loading a saved index).
    if args.demo:
        chunks = sample_chunks()
    elif args.data:
        folder = Path(args.data)
        chunks = []
        for path in sorted(folder.rglob("*")):
            if path.suffix.lower() in {".txt", ".md"} and path.is_file():
                chunks.extend(chunk_text(
                    path.read_text(encoding="utf-8", errors="ignore"),
                    source=path.name,
                    size=args.chunk_size,
                    overlap=args.chunk_overlap,
                ))
        if not chunks:
            print(f"No .txt or .md files found in: {folder}", file=sys.stderr)
            return 1
    else:  # --load-index without a corpus: citations fall back to uids only
        chunks = sample_chunks()

    app = TxtaiRAGApp(chunks=chunks, llm_path=args.model, context=args.context)

    if args.load_index:
        app.load_index(args.load_index, chunks)
    else:
        app.build_index(save_path=args.save_index)

    did_something = False
    if args.search:
        app.print_search(args.search, limit=args.limit)
        did_something = True
    if args.ask:
        app.print_ask(args.ask)
        did_something = True

    if args.interactive:
        print("\nInteractive mode — ask a question, prefix with 'search:' "
              "for raw search, 'quit' to exit.")
        while True:
            try:
                line = input("\n> ").strip()
            except (EOFError, KeyboardInterrupt):
                print()
                break
            if not line or line.lower() in {"quit", "exit", "q"}:
                break
            if line.lower().startswith("search:"):
                app.print_search(line.split(":", 1)[1].strip(), limit=args.limit)
            else:
                app.print_ask(line)
        did_something = True

    if not did_something:
        # No action requested: show the search tab equivalent as a smoke test.
        app.print_search("What was won?" if args.demo else "search", limit=args.limit)
        print("\nTip: add --ask \"...\", --search \"...\", or --interactive.")
    return 0


if __name__ == "__main__":
    # Avoid noisy HF warnings in demos; remove if you want full logging.
    os.environ.setdefault("TOKENIZERS_PARALLELISM", "false")
    raise SystemExit(main())
